#!/usr/bin/env python3
"""Generate the BeamNG-derived vehicle files from your local BeamNG.tech install.

The repository ships no BeamNG files. Each recipe in ``vehicles/recipes/`` pins
the stock entries of ``content/vehicles/sbr.zip`` it reads (BeamNG.tech 0.38.3)
and describes one vehicle file as references to, and edits of, those lines.
Every output is checked against its pinned sha256 before anything is written.

    python scripts/build_vehicles.py                  # writes vehicles/sbr/
    python scripts/build_vehicles.py --check          # verify generated files only
    python scripts/build_vehicles.py --out-dir DIR    # write into DIR instead

BeamNG home: ``--beamng-home``, else ``DARTS_BNG_HOME`` / ``BEAMNG_HOME``, else
``C:/BeamNG.tech``.

Recipe format (one JSON file per output):

    output         repo-relative path of the generated file
    output_sha256  sha256 of the generated bytes
    beamng         BeamNG.tech release the sources are pinned to
    archive        stock archive, relative to the BeamNG home
    sources        [[entry, sha256], ...]; ops refer to these by index
    newline        separator the output lines are joined with
    ops            each op appends output lines, in order:
      ["R", src, line, count, lead, trail, blank]  stock lines line .. line+count-1
      ["E", src, line, lead, trail, edits]         one stock line; edits are
                                                   [[start, end, insert], ...] applied
                                                   to its whitespace-stripped text
      ["W", text, count]                           whitespace-only line, repeated
      ["L", text]                                  line with no stock counterpart

``lead`` / ``trail`` replace a stock line's leading / trailing whitespace (a
trailing carriage return counts as whitespace) and ``blank`` replaces a
whitespace-only stock line; ``null`` keeps the stock whitespace. Line numbers
are 0-based over the entry split on ``\\n``.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
import tempfile
import zipfile
from pathlib import Path, PurePosixPath

REPO = Path(__file__).resolve().parents[1]
RECIPES = REPO / "vehicles" / "recipes"
DEFAULT_HOME = "C:/BeamNG.tech"
RECIPE_VERSION = 1


class RecipeError(RuntimeError):
    """A recipe is malformed, its sources do not match, or its output does not verify."""


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def resolve_home(cli_home: str | None = None) -> Path:
    for value in (cli_home, os.environ.get("DARTS_BNG_HOME"), os.environ.get("BEAMNG_HOME")):
        if value and value.strip():
            return Path(value.strip())
    return Path(DEFAULT_HOME)


def load_recipe(path: Path) -> dict:
    try:
        recipe = json.loads(path.read_text(encoding="utf-8"))
        version = recipe.get("recipe_version")
        out = PurePosixPath(recipe["output"])
    except (AttributeError, KeyError, TypeError, ValueError) as exc:
        raise RecipeError(f"{path.name}: unreadable recipe ({exc})") from None
    if version != RECIPE_VERSION:
        raise RecipeError(f"{path.name}: unsupported recipe_version {version!r}")
    if out.is_absolute() or ".." in out.parts:
        raise RecipeError(f"{path.name}: output must be a relative path inside the repository")
    return recipe


def _whitespace(value, what: str) -> None:
    if value is not None and (not isinstance(value, str) or value.strip() or "\n" in value):
        raise RecipeError(f"{what} must be null or whitespace without newlines, got {value!r}")


def _restyle(line: str, lead, trail, blank, core: str | None = None) -> str:
    stripped = line.strip()
    if not stripped:
        if core is not None:
            raise RecipeError("character edits need a stock line with text")
        return line if blank is None else blank
    if lead is None:
        lead = line[: len(line) - len(line.lstrip())]
    if trail is None:
        trail = line[len(line.rstrip()):]
    return lead + (stripped if core is None else core) + trail


def _apply_edits(text: str, edits) -> str:
    pieces, pos = [], 0
    for start, end, insert in edits:
        if not (pos <= start <= end <= len(text)) or not isinstance(insert, str) or "\n" in insert:
            raise RecipeError(f"bad edit {[start, end, insert]!r} on a {len(text)}-character line")
        pieces.append(text[pos:start])
        pieces.append(insert)
        pos = end
    pieces.append(text[pos:])
    return "".join(pieces)


def _source_lines(sources: list[list[str]], src: int, start: int, count: int) -> list[str]:
    if not (0 <= src < len(sources) and start >= 0 and count >= 1 and start + count <= len(sources[src])):
        raise RecipeError(f"lines {start}+{count} of source {src} do not exist")
    return sources[src][start:start + count]


def render(recipe: dict, sources: list[list[str]]) -> bytes:
    """Rebuild the output bytes from the verified, newline-split source entries."""
    lines: list[str] = []
    for op in recipe["ops"]:
        kind = op[0]
        if kind == "R":
            _, src, start, count, lead, trail, blank = op
            for value, what in ((lead, "lead"), (trail, "trail"), (blank, "blank")):
                _whitespace(value, what)
            lines.extend(_restyle(line, lead, trail, blank) for line in _source_lines(sources, src, start, count))
        elif kind == "E":
            _, src, idx, lead, trail, edits = op
            _whitespace(lead, "lead")
            _whitespace(trail, "trail")
            line = _source_lines(sources, src, idx, 1)[0]
            lines.append(_restyle(line, lead, trail, None, _apply_edits(line.strip(), edits)))
        elif kind == "W":
            _, text, count = op
            if not isinstance(text, str):
                raise RecipeError(f"bad whitespace line {text!r}")
            _whitespace(text, "whitespace line")
            lines.extend([text] * count)
        elif kind == "L":
            if not isinstance(op[1], str) or "\n" in op[1]:
                raise RecipeError(f"bad literal line {op[1]!r}")
            lines.append(op[1])
        else:
            raise RecipeError(f"unknown op {kind!r}")
    return recipe["newline"].join(lines).encode("utf-8")


class StockArchive:
    """Read-only view of a stock archive with per-entry sha256 checks."""

    def __init__(self, home: Path, archive: str, release: str):
        self.path = Path(home) / archive
        self.release = release
        if not self.path.is_file():
            raise RecipeError(f"{self.path} not found; point --beamng-home or DARTS_BNG_HOME "
                              f"at a {release} install")
        self._zip = zipfile.ZipFile(self.path)
        self._lines: dict[tuple[str, str], list[str]] = {}

    def close(self) -> None:
        self._zip.close()

    def lines(self, entry: str, digest: str) -> list[str]:
        key = (entry, digest)
        if key not in self._lines:
            try:
                data = self._zip.read(entry)
            except KeyError:
                raise RecipeError(f"{entry} is missing from {self.path}; the recipes need {self.release}") from None
            if sha256(data) != digest:
                raise RecipeError(f"{entry} in {self.path} does not match the pinned sha256 "
                                  f"{digest[:12]}...; the recipes need {self.release}")
            self._lines[key] = data.decode("utf-8").split("\n")
        return self._lines[key]


def build_one(recipe: dict, archives: dict[str, StockArchive], home: Path) -> bytes:
    archive = archives.get(recipe["archive"])
    if archive is None:
        archive = archives[recipe["archive"]] = StockArchive(home, recipe["archive"], recipe["beamng"])
    sources = [archive.lines(entry, digest) for entry, digest in recipe["sources"]]
    try:
        data = render(recipe, sources)
    except (IndexError, KeyError, TypeError, ValueError) as exc:
        raise RecipeError(f"{recipe['output']}: malformed recipe ({exc})") from None
    if sha256(data) != recipe["output_sha256"]:
        raise RecipeError(f"{recipe['output']}: generated bytes do not match the pinned sha256")
    return data


def target_path(recipe: dict, out_dir: Path | None) -> Path:
    rel = PurePosixPath(recipe["output"])
    return (Path(out_dir) / rel.name) if out_dir else REPO.joinpath(*rel.parts)


def write_atomic(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def check(recipes: list[dict], out_dir: Path | None = None) -> list[str]:
    """Problems with already generated files; empty when all match their pinned sha256."""
    problems = []
    for recipe in recipes:
        path = target_path(recipe, out_dir)
        if not path.is_file():
            problems.append(f"missing {path}")
        elif sha256(path.read_bytes()) != recipe["output_sha256"]:
            problems.append(f"differs {path}")
    return problems


def build(recipes: list[dict], home: Path, out_dir: Path | None = None) -> list[tuple[Path, bool]]:
    """Verify every recipe first, then write; returns (path, changed) per output."""
    archives: dict[str, StockArchive] = {}
    try:
        outputs = [(target_path(r, out_dir), build_one(r, archives, home)) for r in recipes]
    finally:
        for archive in archives.values():
            archive.close()
    written = []
    for path, data in outputs:
        changed = not (path.is_file() and path.read_bytes() == data)
        if changed:
            write_atomic(path, data)
        written.append((path, changed))
    return written


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--beamng-home", help="BeamNG.tech install (default: DARTS_BNG_HOME, BEAMNG_HOME, C:/BeamNG.tech)")
    ap.add_argument("--check", action="store_true", help="only verify already generated files; write nothing")
    ap.add_argument("--out-dir", type=Path, help="write the generated files into this directory")
    args = ap.parse_args(argv)
    paths = sorted(RECIPES.glob("*.json"))
    if not paths:
        print(f"no recipes in {RECIPES}", file=sys.stderr)
        return 1
    try:
        recipes = [load_recipe(p) for p in paths]
        if args.check:
            problems = check(recipes, args.out_dir)
            for line in problems:
                print(line, file=sys.stderr)
            print(f"{len(recipes) - len(problems)}/{len(recipes)} generated files match their recipes")
            return 1 if problems else 0
        home = resolve_home(args.beamng_home)
        results = build(recipes, home, args.out_dir)
    except RecipeError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    for path, changed in results:
        shown = path.relative_to(REPO) if path.is_relative_to(REPO) else path
        print(f"{'wrote' if changed else 'unchanged'} {shown.as_posix()}")
    print(f"{len(results)} vehicle files generated from {home} ({recipes[0]['beamng']})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
